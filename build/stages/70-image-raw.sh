#!/usr/bin/env bash
#
# Stage 70 - build a ready-to-flash raw disk image.
#
# The arm64 appliance path: many SBCs and arm64 servers are far happier being
# handed a pre-installed disk image than booting an installer. Produces a GPT
# image with the same layout AX-Installer creates, so a machine flashed from
# this image is indistinguishable from one installed interactively.
#
# Also available for amd64 (AXOS_BUILD_RAW=1), which is useful for VM templates.

set -euo pipefail
AXOS_ROOT="${AXOS_ROOT:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)}"
# shellcheck source=../lib/common.sh
source "$AXOS_ROOT/build/lib/common.sh"
# shellcheck source=../config/build.conf
source "$AXOS_ROOT/build/config/build.conf"

if [[ "$AXOS_ARCH" == "amd64" ]] && [[ "${AXOS_BUILD_RAW:-0}" != "1" ]]; then
    info "skipping raw image for amd64 (set AXOS_BUILD_RAW=1 to build one)"
    exit 0
fi

require_root
[[ -d "$AXOS_ROOTFS" ]] || die "no rootfs at $AXOS_ROOTFS - run stage 10 first"
need_cmd losetup sgdisk mkfs.vfat mkfs.btrfs rsync

limine_dir="$AXOS_WORKDIR/limine"
[[ -d "$limine_dir" ]] || die "Limine not staged - run stage 40 first"

img="$AXOS_DISTDIR/${AXOS_IMAGE_BASENAME}.img"
mnt="$AXOS_WORKDIR/raw-mnt"
loop=""

cleanup_raw() {
    axos_umount_all
    [[ -n "$loop" ]] && losetup -d "$loop" 2>/dev/null || true
}
trap cleanup_raw EXIT INT TERM

mkdir -p "$AXOS_DISTDIR"
rm -f "$img"

log "allocating a ${AXOS_RAW_IMAGE_MIB}MiB image"
truncate -s "${AXOS_RAW_IMAGE_MIB}M" "$img"

# Partition layout mirrors internal/install/plan.go for UEFI:
#   1 = FAT32 boot/ESP - Limine cannot read btrfs, so the kernel lives here
#   2 = btrfs root
sgdisk --zap-all "$img" >/dev/null
sgdisk \
    --new=1:0:+"${AXOS_ESP_SIZE_MIB}"M --typecode=1:ef00 --change-name=1:AXOS-ESP \
    --new=2:0:0                        --typecode=2:8300 --change-name=2:AXOS-ROOT \
    "$img" >/dev/null

loop="$(losetup --find --show --partscan "$img")"
[[ -n "$loop" ]] || die "could not attach a loop device"
udevadm settle --timeout=30 2>/dev/null || true
ok "attached $loop"

boot_dev="${loop}p1"
root_dev="${loop}p2"

mkfs.vfat -F 32 -n AXOS-BOOT "$boot_dev" >/dev/null
mkfs.btrfs -f -L AXOS "$root_dev" >/dev/null

# Subvolumes, matching BtrfsSubvolumes in plan.go.
rm -rf -- "$mnt"; mkdir -p "$mnt"
axos_mount "$root_dev" "$mnt" -o noatime
for sv in @ @home @log @cache @snapshots @docker @containers @srv; do
    btrfs subvolume create "$mnt/$sv" >/dev/null
done
chattr +C "$mnt/@docker" "$mnt/@containers" 2>/dev/null || true
axos_umount_all

axos_mount "$root_dev" "$mnt" -o "noatime,compress=zstd:3,subvol=@"
for pair in "@home:/home" "@log:/var/log" "@cache:/var/cache" "@snapshots:/.snapshots" \
            "@docker:/var/lib/docker" "@containers:/var/lib/containers" "@srv:/srv"; do
    sv="${pair%%:*}"; at="${pair##*:}"
    mkdir -p "$mnt$at"
    opts="noatime,subvol=$sv"
    case "$sv" in
        @docker|@containers) opts="$opts,nodatacow" ;;
        *)                   opts="$opts,compress=zstd:3" ;;
    esac
    axos_mount "$root_dev" "$mnt$at" -o "$opts"
done

mkdir -p "$mnt/boot"
axos_mount "$boot_dev" "$mnt/boot" -o umask=0077

log "copying the root filesystem into the image"
rsync -aHAXx --numeric-ids \
    --exclude='/dev/*' --exclude='/proc/*' --exclude='/sys/*' \
    --exclude='/run/*' --exclude='/tmp/*' --exclude='/mnt/*' \
    --exclude='/var/cache/apt/archives/*.deb' --exclude='/var/lib/apt/lists/*' \
    "$AXOS_ROOTFS/" "$mnt/" || die "rsync into the image failed"

root_uuid="$(blkid -o value -s UUID "$root_dev")"
boot_uuid="$(blkid -o value -s UUID "$boot_dev")"

cat > "$mnt/etc/fstab" <<FSTAB
# /etc/fstab - generated by build/stages/70-image-raw.sh
UUID=$root_uuid  /                   btrfs  noatime,compress=zstd:3,subvol=@,space_cache=v2       0 0
UUID=$root_uuid  /home               btrfs  noatime,compress=zstd:3,subvol=@home,space_cache=v2   0 0
UUID=$root_uuid  /var/log            btrfs  noatime,compress=zstd:3,subvol=@log,space_cache=v2    0 0
UUID=$root_uuid  /var/cache          btrfs  noatime,compress=zstd:3,subvol=@cache,space_cache=v2  0 0
UUID=$root_uuid  /.snapshots         btrfs  noatime,subvol=@snapshots,space_cache=v2              0 0
UUID=$root_uuid  /var/lib/docker     btrfs  noatime,nodatacow,subvol=@docker,space_cache=v2       0 0
UUID=$root_uuid  /var/lib/containers btrfs  noatime,nodatacow,subvol=@containers,space_cache=v2   0 0
UUID=$root_uuid  /srv                btrfs  noatime,compress=zstd:3,subvol=@srv,space_cache=v2    0 0
UUID=$boot_uuid  /boot               vfat   umask=0077,shortname=winnt                            0 2

tmpfs /tmp tmpfs defaults,noatime,nosuid,nodev,size=2G 0 0
FSTAB

# ---------------------------------------------------------------------------
# Bootloader
# ---------------------------------------------------------------------------
kernel_ver="$(axos_debian_kernel "$AXOS_ROOTFS")"
efi_stub="$(axos_efi_stub "$AXOS_ARCH")"

install -Dm0644 "$limine_dir/$efi_stub" "$mnt/boot/EFI/BOOT/$efi_stub"
install -Dm0644 "$limine_dir/$efi_stub" "$mnt/boot/EFI/andersxn/$efi_stub"
if [[ -f "$AXOS_WORKDIR/splash.png" ]]; then
    install -Dm0644 "$AXOS_WORKDIR/splash.png" "$mnt/boot/andersxn/splash.png"
fi

sed -e "s|@ROOT_SPEC@|UUID=$root_uuid|g" \
    -e "s|@KERNEL@|/vmlinuz-$kernel_ver|g" \
    -e "s|@INITRD@|/initrd.img-$kernel_ver|g" \
    -e "s|@NAME@|$AXOS_NAME|g" \
    -e "s|@VERSION@|$AXOS_VERSION|g" \
    -e "s|@CODENAME@|$AXOS_CODENAME|g" \
    -e "s|@INK@|$AXOS_HEX_INK|g" \
    -e "s|@SNOW@|$AXOS_HEX_SNOW|g" \
    "$AXOS_ROOT/branding/limine/limine.conf.in" > "$mnt/boot/limine.conf"

# ---------------------------------------------------------------------------
# Raspberry Pi boot path (arm64)
#
# The Pi has no UEFI. Its bootloader reads config.txt from the ROOT of the FAT
# partition and loads the kernel, initramfs and device tree itself. Those files
# sit alongside the EFI directory generic arm64 machines boot from, and each
# firmware ignores the other's - so one image boots both.
#
# The Pi path loads the Raspberry Pi Foundation kernel, NOT Debian's. Debian's
# mainline arm64 kernel cannot drive a Pi 5's storage or RP1 southbridge, and
# a Pi 5 booting it lands in an initramfs shell with no root device. Limine's
# UEFI path still boots Debian's kernel; only the Pi path differs.
# ---------------------------------------------------------------------------
if [[ "$AXOS_ARCH" == "arm64" ]]; then
    log "adding the Raspberry Pi boot path"

    # Newest kernel of each flavour. rpi-2712 is the Pi 5; rpi-v8 covers the
    # Pi 4, 400, CM4, Pi 3 and Zero 2 W. They are genuinely different builds,
    # so config.txt picks between them by board rather than shipping one.
    pi5_kernel="$(ls -1 "$AXOS_ROOTFS"/boot/vmlinuz-*-rpi-2712 2>/dev/null | sort -V | tail -1 || true)"
    pi4_kernel="$(ls -1 "$AXOS_ROOTFS"/boot/vmlinuz-*-rpi-v8 2>/dev/null | sort -V | tail -1 || true)"
    [[ -n "$pi5_kernel" && -n "$pi4_kernel" ]] ||
        die "Raspberry Pi kernels are missing from the rootfs - stage 25 should
    have installed $AXOS_PKGS_PI_KERNEL"

    pi5_ver="$(basename "$pi5_kernel" | sed 's/^vmlinuz-//')"
    pi4_ver="$(basename "$pi4_kernel" | sed 's/^vmlinuz-//')"
    info "Pi 5 kernel: $pi5_ver"
    info "Pi 4 kernel: $pi4_ver"

    fw="$AXOS_ROOTFS/usr/lib/raspi-firmware"
    if [[ -d "$fw" ]]; then
        # start*.elf, fixup*.dat, bootcode.bin. The Pi 5 loads its firmware
        # from EEPROM and ignores these; the Pi 4 and earlier need them here.
        cp -a "$fw"/*.elf "$fw"/*.dat "$mnt/boot/" 2>/dev/null || true
        cp -a "$fw"/bootcode.bin "$mnt/boot/" 2>/dev/null || true
        ok "Pi firmware blobs copied"
    else
        warn "no raspi-firmware in the rootfs - this image will not boot a Pi"
    fi

    # Device trees and overlays, from the Foundation kernel packages. These
    # carry the Pi overlays Debian's kernel has none of - vc4-kms-v3d among
    # them, which is what gives the desktop an accelerated display.
    for ver in "$pi5_ver" "$pi4_ver"; do
        for sub in broadcom ""; do
            d="$AXOS_ROOTFS/usr/lib/linux-image-$ver${sub:+/$sub}"
            [[ -d "$d" ]] || continue
            cp -a "$d"/bcm*.dtb "$mnt/boot/" 2>/dev/null || true
        done
        ov="$AXOS_ROOTFS/usr/lib/linux-image-$ver/overlays"
        if [[ -d "$ov" ]]; then
            mkdir -p "$mnt/boot/overlays"
            cp -a "$ov"/. "$mnt/boot/overlays/" 2>/dev/null || true
        fi
    done
    ok "device trees copied ($(ls -1 "$mnt/boot"/bcm*.dtb 2>/dev/null | wc -l) files, $(ls -1 "$mnt/boot/overlays" 2>/dev/null | wc -l) overlays)"

    # The display overlay is per board, not one global setting. The Pi 5's
    # BCM2712 pipeline needs vc4-kms-v3d-pi5, the Pi 4 needs -pi4, and only
    # the Pi 3 and earlier take the plain one. Applying the generic overlay to
    # a Pi 5 leaves it with no KMS, so /dev/dri never appears, X cannot start
    # and the board boots to a text console.
    pick_overlay() {
        local want
        for want in "$@"; do
            if [[ -f "$mnt/boot/overlays/${want}.dtbo" ]]; then
                printf 'dtoverlay=%s\n' "$want"
                return
            fi
        done
        printf '# no vc4 overlay found for this board\n'
    }
    kms_pi5="$(pick_overlay vc4-kms-v3d-pi5 vc4-kms-v3d)"
    kms_pi4="$(pick_overlay vc4-kms-v3d-pi4 vc4-kms-v3d)"
    kms_pi3="$(pick_overlay vc4-kms-v3d)"
    info "display overlays: pi5=${kms_pi5#dtoverlay=} pi4=${kms_pi4#dtoverlay=} pi3=${kms_pi3#dtoverlay=}"

    cat > "$mnt/boot/config.txt" <<PICONF
# $AXOS_NAME $AXOS_VERSION - Raspberry Pi boot configuration.
#
# Read by the Pi bootloader from the root of this partition. Generic arm64
# machines boot EFI/BOOT/ instead and never look at this file.
#
# Kernel AND display overlay are chosen per board. The Pi 5 and Pi 4 need
# different builds of both; nothing here is safe to hoist into [all].

arm_64bit=1
enable_uart=1
disable_overscan=1
max_framebuffers=2

[pi5]
kernel=vmlinuz-$pi5_ver
initramfs initrd.img-$pi5_ver followkernel
$kms_pi5
dtparam=pciex1

[pi4]
kernel=vmlinuz-$pi4_ver
initramfs initrd.img-$pi4_ver followkernel
$kms_pi4

[pi3]
kernel=vmlinuz-$pi4_ver
initramfs initrd.img-$pi4_ver followkernel
$kms_pi3

[all]
PICONF

    # cmdline.txt must be ONE line - the Pi firmware passes it verbatim and a
    # newline silently truncates the kernel command line.
    printf '%s\n' "console=serial0,115200 console=tty1 root=UUID=$root_uuid rootfstype=btrfs rootflags=subvol=@ rw fsck.repair=yes rootwait quiet splash" \
        > "$mnt/boot/cmdline.txt"

    # raspi-firmware also populates /boot/firmware, which rsync copied onto
    # this partition. The Pi only reads the partition root, so that tree is
    # duplicate DTBs and blobs occupying space for nothing.
    rm -rf "$mnt/boot/firmware"

    # -----------------------------------------------------------------------
    # Keep config.txt pointing at the current kernels
    #
    # config.txt names kernel files explicitly and the Pi bootloader has no
    # notion of "newest". Debian's raspi-firmware hook maintains
    # /boot/firmware, which is NOT where this layout keeps things - AndersXn
    # mounts the FAT at /boot so Limine can read it too. Without this, the next
    # kernel upgrade would land a new vmlinuz here while config.txt still named
    # the old one, and the Pi would boot a kernel whose modules had just been
    # removed.
    # -----------------------------------------------------------------------
    install -Dm0755 /dev/stdin "$mnt/etc/kernel/postinst.d/zz-axos-pi-config" <<'PIHOOK'
#!/bin/sh
# Repoint /boot/config.txt at the newest kernel of each Pi flavour.
set -eu

conf=/boot/config.txt
[ -f "$conf" ] || exit 0

tmp="$(mktemp)"
cp "$conf" "$tmp"

for flavour in 2712 v8; do
    newest="$(ls -1 /boot/vmlinuz-*-rpi-$flavour 2>/dev/null | sort -V | tail -1 || true)"
    [ -n "$newest" ] || continue
    kver="${newest#/boot/vmlinuz-}"
    [ -f "/boot/initrd.img-$kver" ] || continue

    # Rewrite only inside the matching [piN] section, so the Pi 5 and Pi 4
    # entries never overwrite one another.
    case "$flavour" in
        2712) sections="pi5" ;;
        v8)   sections="pi4 pi3" ;;
    esac
    for sec in $sections; do
        awk -v sec="[$sec]" -v k="vmlinuz-$kver" -v i="initrd.img-$kver" '
            /^\[/ { cur = $0 }
            cur == sec && /^kernel=/    { print "kernel=" k; next }
            cur == sec && /^initramfs / { print "initramfs " i " followkernel"; next }
            { print }
        ' "$tmp" > "$tmp.new" && mv "$tmp.new" "$tmp"
    done
done

cat "$tmp" > "$conf"
rm -f "$tmp"
echo "axos: config.txt updated for the current Pi kernels"
PIHOOK
    ok "kernel hook installed to keep config.txt current"
    ok "Pi boot path written (config.txt, cmdline.txt)"
fi

# ---------------------------------------------------------------------------
# First-boot expansion
#
# The image is built at a fixed size; the card or disk it gets flashed onto is
# almost never that size. This grows root to fill whatever it lands on, once.
# ---------------------------------------------------------------------------
install -Dm0644 /dev/stdin "$mnt/etc/systemd/system/axos-growfs.service" <<'UNIT'
[Unit]
Description=Expand the AndersXn root filesystem to fill the disk
After=local-fs.target
ConditionPathExists=!/var/lib/andersxn/.growfs-done

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/lib/andersxn/growfs
ExecStartPost=/usr/bin/touch /var/lib/andersxn/.growfs-done

[Install]
WantedBy=multi-user.target
UNIT

install -Dm0755 /dev/stdin "$mnt/usr/lib/andersxn/growfs" <<'GROW'
#!/bin/sh
# Grow the GPT root partition and the btrfs filesystem inside it to fill the
# device. Runs once, on the first boot after flashing.
set -eu

root_src="$(findmnt -no SOURCE / | sed 's/\[.*\]//')"
part_name="$(basename "$root_src")"
disk="/dev/$(lsblk -no PKNAME "$root_src" | head -1)"
partnum="$(cat "/sys/class/block/$part_name/partition")"

# The backup GPT header sits at the end of the IMAGE, not the end of the disk;
# it has to be relocated before the last partition can be extended.
sgdisk --move-second-header "$disk" >/dev/null 2>&1 || true

if command -v growpart >/dev/null 2>&1; then
    growpart "$disk" "$partnum" >/dev/null 2>&1 || true
else
    # cloud-guest-utils is not installed: do it with sgdisk directly.
    start="$(sgdisk --info="$partnum" "$disk" | awk '/First sector/ {print $3}')"
    sgdisk --delete="$partnum" "$disk" >/dev/null 2>&1 || true
    sgdisk --new="$partnum:$start:0" --typecode="$partnum:8300" \
           --change-name="$partnum:AXOS-ROOT" "$disk" >/dev/null 2>&1 || true
fi

partprobe "$disk" >/dev/null 2>&1 || true
btrfs filesystem resize max / >/dev/null 2>&1 || true
GROW

chroot "$mnt" systemctl enable axos-growfs.service >/dev/null 2>&1 || true

sync
axos_umount_all
losetup -d "$loop"; loop=""

( cd "$AXOS_DISTDIR" && sha256sum "$(basename "$img")" > "$(basename "$img").sha256" )
ok "raw image ready: $img ($(du -h "$img" | cut -f1))"

# Raw images are compressed with xz, not zstd.
#
# This artifact exists to be written to an SD card or USB stick, and the tools
# people actually use for that - Raspberry Pi Imager, balenaEtcher - decompress
# .xz natively but not .zst. Shipping zstd here would mean every user has to
# decompress a 9GB file by hand first. The ISO still uses zstd, which is only
# ever decompressed by us.
if [[ "${AXOS_COMPRESS:-1}" == "1" ]] && command -v xz >/dev/null 2>&1; then
    log "compressing the release artifact (xz, for flashing tools)"
    # -T0 uses every core; -6 is the point where xz stops buying much for the
    # time it costs on this class of machine.
    xz -T0 -6 -k -f -c "$img" > "${img}.xz"
    ( cd "$AXOS_DISTDIR" && sha256sum "$(basename "$img").xz" > "$(basename "$img").xz.sha256" )
    ok "compressed: ${img}.xz ($(du -h "${img}.xz" | cut -f1))"
elif [[ "${AXOS_COMPRESS:-1}" == "1" ]]; then
    warn "xz not installed - shipping the raw image uncompressed"
    warn "install xz-utils for an image flashing tools can read directly"
fi
